def oc_match(inp: str, pattern: str, win: bool = WIN) -> bool:
    """A Python port of OpenCode's Wildcard.match (packages/core/src/util/wildcard.ts@v1.18.34)."""
    inp = inp.replace("\\", "/")
    esc = re.sub(r"[.+^${}()|\[\]\\]", lambda m: "\\" + m.group(0), pattern.replace("\\", "/"))
    esc = esc.replace("*", ".*").replace("?", ".")
    if esc.endswith(" .*"):
        esc = esc[:-3] + "( .*)?"
    return re.fullmatch(esc, inp, re.S | (re.I if win else 0)) is not None


def driveless(p) -> str:
    s = str(p).replace("\\", "/")
    return re.sub(r"^[A-Za-z]:", "", s).lstrip("/")


