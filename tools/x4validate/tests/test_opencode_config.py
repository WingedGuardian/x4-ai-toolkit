def run(env, action, root, *extra):
    r = subprocess.run([sys.executable, str(root / ".opencode" / "hooks" / "opencode_config.py"), action,
                        "--root", str(root), *extra], capture_output=True, env=env, timeout=120)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def rendered(env, root) -> dict:
    rc, out, err = run(env, "render", root)
    assert rc == 0, err
    first, _, body = out.partition("\n")
    assert first.startswith("// GENERATED by .opencode/hooks/opencode_config.py for ")
    lines = [ln for ln in out.splitlines() if not ln.startswith("//")]
    return json.loads("\n".join(lines))


def denied(perm: dict, key: str, inp: str) -> bool:
    return any(oc_match(inp, pat) for pat, act in perm[key].items() if act == "deny")


