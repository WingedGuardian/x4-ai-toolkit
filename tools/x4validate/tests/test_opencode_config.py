"""The OpenCode permission config renderer (Plan 3 lane L Task 4): the PRIMARY OpenCode layer,
explicit deny rules rendered per machine from the roots the GUARDS resolve.

What OpenCode feeds its matcher (path.relative(worktree, file), `\\` folded, case-insensitive on
Windows) is READ from its v1.18.34 source; the matcher itself is checked here two ways: a Python
port (oc_match) and OpenCode's OWN match() vendored as fixtures/opencode/wildcard-v1.18.34.mts and
run under node over the same table. Nothing here runs OpenCode (user decision: no local install).
"""
