def _table(ref):
    d = driveless(ref)
    return [  # (input as OpenCode builds it, should_deny)  -- the M1 shapes
        (d + "/a.xml", True),                                   # worktree "/" on Windows: drive-less
        ("../../../" + d + "/l/w.xml", True),                   # a `..` chain out of the worktree
        ((d + "/a.xml").replace("/", "\\"), True),              # backslashes
        ("C:/" + d.upper() + "/A.XML", WIN),                    # other case: Windows only
        (d + "-backup/a.xml", False),
        ("Q:/X4/reference/a.xml", False),
        ("dev/m/libraries/wares.xml", False),
        ("reference/a.xml", False),                             # this reference is NOT in the worktree
    ]


def test_rendered_edit_rules_deny_exactly_the_reference_forms(box):
    root, ref, game, env = box
    perm = rendered(env, root)["permission"]
    got = [(inp, denied(perm, "edit", inp)) for inp, _ in _table(ref)]
    assert got == _table(ref)


