"""Agent-neutral launcher: start any coding agent from the install folder, whatever folder the terminal opened in.

An agent loads its hooks and instructions from the folder it is started in. Started from some other folder, it runs
with no guards and none of the toolkit's text, and nothing inside the toolkit can notice that. The one lever that
works for every agent is to change into the install folder first, so this writes a small script that does exactly that
and then starts the chosen agent.

It names no agent: the calling toolkit passes `{name: command}`, and `-- <command> [args]` starts any other.
It edits no PATH, no shell profile and no agent configuration. It writes only the files it is asked for, and refuses
to overwrite a file it did not write.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import uuid
from pathlib import Path

MARKER = "Generated by modding_harness.launcher"
SHELLS = ("bash", "powershell", "cmd")
SUFFIX = {"bash": "", "powershell": ".ps1", "cmd": ".cmd"}

_TOKEN = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]*\Z")      # an agent name or a command: one plain word, no shell syntax
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*\Z")         # the launcher's own file name: no dot, no path part
_DEVICE = re.compile(r"(?i)(con|prn|aux|nul|com[1-9]|lpt[1-9])\Z")
# PowerShell reads all of these as single quotes inside a '...' literal, so each must be doubled, not only the ASCII one.
_PS_QUOTES = "'‘’‚‛"


def quote_path(value, shell):
    """The path as one literal for `shell`, with no way for its characters to be read as syntax."""
    value = os.fspath(value)
    if not value or any(ch in value for ch in "\x00\r\n"):
        raise ValueError("the install folder path is empty or holds a control character")
    if shell == "bash":
        return "'" + value.replace("'", "'\\''") + "'"
    if shell == "powershell":
        return "'" + "".join(ch + ch if ch in _PS_QUOTES else ch for ch in value) + "'"
    if shell == "cmd":
        # The value sits inside set "ROOT=..." with delayed expansion off: inside double quotes only % still means
        # something (doubled it is literal), and a double quote cannot occur in a Windows path, so one is refused.
        if '"' in value:
            raise ValueError("a double quote cannot be carried in a .cmd launcher")
        return value.replace("%", "%%")
    raise ValueError("no path literal for shell %r" % (shell,))


def _check_agents(agents):
    if not isinstance(agents, dict) or not agents:
        raise ValueError("agents must be a non-empty {name: command} mapping")
    for name, command in agents.items():
        if not isinstance(name, str) or not _TOKEN.fullmatch(name):
            raise ValueError("invalid agent name %r" % (name,))
        if not isinstance(command, str) or not _TOKEN.fullmatch(command):
            raise ValueError("invalid agent command %r for %s (one plain word; arguments follow on the command line)"
                             % (command, name))
    return dict(agents)


def _check_name(name):
    if not isinstance(name, str) or not _NAME.fullmatch(name) or _DEVICE.fullmatch(name):
        raise ValueError("invalid launcher name %r" % (name,))
    return name


def _bash(root, agents):
    usage = ['echo "usage: $(basename "$0") <agent> [args...]"',
             'echo "agents: %s"' % ", ".join("%s (%s)" % item for item in agents.items()),
             'echo "any other: $(basename "$0") -- <command> [args...]"']
    cases = "".join('  %s) shift; exec %s "$@" ;;\n' % (name, command) for name, command in agents.items())
    return (
        "#!/usr/bin/env bash\n"
        "# %s. Starts a coding agent from the install folder. Edits no PATH, no profile, no agent configuration.\n"
        "set -u\n"
        "ROOT=%s\n"
        'if [ ! -d "$ROOT" ]; then\n'
        '  echo "install folder not found: $ROOT (rewrite this launcher with the toolkit installer)" >&2\n'
        "  exit 2\n"
        "fi\n"
        'cd "$ROOT" || exit 2\n'
        "usage() {\n  %s\n}\n"
        'case "${1-}" in\n'
        '  "" | -h | --help | --list) usage; exit 0 ;;\n'
        "%s"
        '  --) shift; [ "$#" -gt 0 ] || { usage >&2; exit 2; }; exec "$@" ;;\n'
        '  *) echo "unknown agent: $1" >&2; usage >&2; exit 2 ;;\n'
        "esac\n"
    ) % (MARKER, quote_path(root, "bash"), "\n  ".join(usage), cases)


def _powershell(root, agents):
    known = "; ".join("'%s' = '%s'" % item for item in agents.items())
    lines = [
        "# %s. Starts a coding agent from the install folder. Edits no PATH, no profile, no agent configuration." % MARKER,
        "$ErrorActionPreference = 'Stop'",
        "$Root = " + quote_path(root, "powershell"),
        "if (-not (Test-Path -LiteralPath $Root -PathType Container)) {",
        '    [Console]::Error.WriteLine("install folder not found: $Root (rewrite this launcher with the toolkit installer)")',
        "    exit 2",
        "}",
        "Set-Location -LiteralPath $Root",
        "$Known = [ordered]@{ %s }" % known,
        "function Show-Usage {",
        "    $me = Split-Path -Leaf $PSCommandPath",
        '    "usage: $me <agent> [args...]"',
        '    "agents: " + (($Known.GetEnumerator() | ForEach-Object { $_.Key + " (" + $_.Value + ")" }) -join ", ")',
        '    "any other: $me -- <command> [args...]"',
        "}",
        "if ($args.Count -eq 0 -or $args[0] -in '-h', '--help', '--list') { Show-Usage; exit 0 }",
        "$first = [string]$args[0]",
        "$rest = @()",
        "if ($args.Count -gt 1) { $rest = @($args[1..($args.Count - 1)]) }",
        "if ($first -eq '--') {",
        "    if ($rest.Count -eq 0) { Show-Usage; exit 2 }",
        "    $cmd = [string]$rest[0]",
        "    $rest = if ($rest.Count -gt 1) { @($rest[1..($rest.Count - 1)]) } else { @() }",
        "} elseif ($Known.Contains($first)) {",
        "    $cmd = $Known[$first]",
        "} else {",
        '    [Console]::Error.WriteLine("unknown agent: $first")',
        "    Show-Usage",
        "    exit 2",
        "}",
        "& $cmd @rest",
        "if ($null -ne $LASTEXITCODE) { exit $LASTEXITCODE }",
    ]
    return "\r\n".join(lines) + "\r\n"


def _cmd(root, agents):
    # Pure cmd, no PowerShell: a stock Windows PC refuses every .ps1 (execution policy "Restricted"), and starting
    # PowerShell with a policy bypass would loosen a setting the user chose. Here the first word is the program to run
    # (`x4 claude --flag`), so the {name: command} table only supplies the usage text. The path is a set "ROOT=..."
    # literal with % doubled and delayed expansion off, and is always shown inside double quotes.
    commands = " ".join(dict.fromkeys(agents.values()))
    return "\r\n".join((
        "@echo off",
        "REM %s. Starts a coding agent from the install folder. Edits no PATH, no profile, no agent configuration." % MARKER,
        "setlocal DisableDelayedExpansion",
        'set "ROOT=%s"' % quote_path(root, "cmd"),
        'if not exist "%ROOT%\\" goto :missing',
        'cd /d "%ROOT%" || exit /b 2',
        'if "%~1"=="" goto :usage',
        'if /i "%~1"=="-h" goto :usage',
        'if /i "%~1"=="--help" goto :usage',
        'if /i "%~1"=="--list" goto :usage',
        "%*",
        "exit /b %ERRORLEVEL%",
        ":usage",
        "echo usage: %~nx0 ^<command^> [args...]",
        "echo starts the command in the install folder, for example: %s" % commands,
        "exit /b 0",
        ":missing",
        'echo install folder not found: "%ROOT%" 1>&2',
        "echo rewrite this launcher with the toolkit installer 1>&2",
        "exit /b 2",
    )) + "\r\n"


def render(workspace, shell, agents, *, name="agent"):
    """The launcher script for `shell`. Refuses a folder that does not exist rather than baking in a wrong place."""
    if shell not in SHELLS:
        raise ValueError("unsupported shell %r (use one of %s)" % (shell, ", ".join(SHELLS)))
    agents = _check_agents(agents)
    _check_name(name)
    root = Path(workspace)
    if not root.is_dir():
        raise ValueError("install folder not found: %s" % (root,))
    root = root.resolve()
    if shell == "bash":
        return _bash(root, agents)
    if shell == "powershell":
        return _powershell(root, agents)
    return _cmd(root, agents)


def _ours(path):
    try:
        with open(path, "rb") as stream:
            return MARKER.encode() in stream.read(1024)
    except OSError:
        return False


def write(workspace, out_dir, agents, *, name="agent", shells=SHELLS):
    """Write `name`, `name.ps1`, `name.cmd` into `out_dir`; return the paths. Nothing is written unless all are allowed."""
    _check_name(name)
    shells = tuple(shells)
    if not shells or set(shells) - set(SHELLS):
        raise ValueError("unsupported shells %r" % (shells,))
    texts = {shell: render(workspace, shell, agents, name=name) for shell in shells}
    out = Path(out_dir)
    targets = {shell: out / (name + SUFFIX[shell]) for shell in shells}
    for target in targets.values():
        if (target.exists() or target.is_symlink()) and not _ours(target):
            raise FileExistsError("refusing to overwrite a file this launcher did not write: %s" % (target,))
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for shell, target in targets.items():
        temporary = target.with_name(target.name + "." + uuid.uuid4().hex[:8] + ".tmp")
        payload = texts[shell].encode("utf-8")                    # bytes, so Windows never translates the line endings
        try:
            with open(temporary, "wb") as stream:
                stream.write(payload)
            if shell == "bash":
                temporary.chmod(temporary.stat().st_mode | 0o111)
            os.replace(temporary, target)
        finally:
            if temporary.exists():
                temporary.unlink()
        written.append(target)
    return written


def main(argv=None, *, default_name="agent"):
    parser = argparse.ArgumentParser(description="Write a launcher that starts a coding agent from the install folder.")
    parser.add_argument("--workspace", required=True, help="the install folder the agent must be started in")
    parser.add_argument("--out", required=True, help="folder to write the launcher into (put it on your PATH yourself)")
    parser.add_argument("--name", default=default_name, help="launcher name (letters, digits, - and _)")
    parser.add_argument("--agent", action="append", default=[], metavar="NAME=COMMAND",
                        help="an agent the launcher lists; repeat for several (e.g. claude=claude)")
    parser.add_argument("--shell", action="append", choices=SHELLS, help="only these shells (default: all three)")
    args = parser.parse_args(argv)
    agents = {}
    for spec in args.agent:
        key, sep, command = spec.partition("=")
        if not sep:
            parser.error("--agent needs NAME=COMMAND, got %r" % spec)
        agents[key] = command
    try:
        paths = write(args.workspace, args.out, agents, name=args.name, shells=tuple(args.shell or SHELLS))
    except (ValueError, OSError) as error:
        print("launcher: " + str(error), file=sys.stderr)
        return 2
    for path in paths:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
