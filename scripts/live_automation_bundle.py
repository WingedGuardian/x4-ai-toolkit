"""Pure own-code Lua bundling and loaded-source attestation. Writes nothing.

Generated bytes are a review/deployment candidate, never a claim of installation.
Module source is normalized to LF before hashing; no game data is consumed.
"""
from __future__ import annotations
import hashlib
import importlib.util
import re
from pathlib import Path

MODULES=("actions","wire","session","automation","menu","transactions","camera","orders",
         "menupages","nativeproviders","playerstate","buildtasks","dialogprobe","paths","logbook","camerastate","people","equipmentmods","ticker","options","playernavigation","timecontrol","nativeassembly","mdchannel",
         "startmenu","startpipe","startbootstrap","bootstrap")
SOURCES={key:f"mods/x4_toolkit_helper/ui/live_{'actionwire' if key=='wire' else key}.lua"
         for key in MODULES}
MARKER='local BUILD = "'+"0"*64+'"'


CAPACITY_SOURCE=Path(__file__).resolve().parents[1]/"tools/x4validate/x4validate/_livecapacity.py"


def capacity_contract(name="interactive"):
    """Read the canonical fixed profiles, with source stability through import."""
    before=CAPACITY_SOURCE.read_bytes()
    spec=importlib.util.spec_from_file_location("bundle_capacity",CAPACITY_SOURCE)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    limits=module.resolve(name);lua=module.lua_source().encode("utf-8")
    if CAPACITY_SOURCE.read_bytes()!=before:
        raise ValueError("capacity source changed during generation")
    return lua,dict(profile=limits["name"],revision=limits["revision"],limits=limits,
        source_path="tools/x4validate/x4validate/_livecapacity.py",
        source_raw_sha256=hashlib.sha256(before).hexdigest(),
        source_normalized_sha256=limits["source_sha256"],
        lua_sha256=hashlib.sha256(lua).hexdigest())


def build(sources: dict[str,bytes], revision: str, *, capacity_profile="interactive"):
    if set(sources)!=set(MODULES) or not re.fullmatch("[0-9a-f]{64}",revision):
        raise ValueError("exact module set and MD revision required")
    capacity_lua,capacity=capacity_contract(capacity_profile)
    pieces=['-- Generated own-code bundle; do not edit.\n',MARKER+'\n',
            'local REVISION = "'+revision+'"\n',
            'local CAPACITY_PROFILE = "'+capacity["profile"]+'"\n',
            'local capacity_resolver=(function()\n'+capacity_lua.decode()+ '\nend)()\n',
            'if type(DebugError)=="function" then DebugError("X4TOOLKIT_AUTOMATION LOAD build="..BUILD) end\n',
            'local previous=rawget(_G,"X4ToolkitAutomationBundle")\n',
            'if previous~=nil then assert(type(previous)=="table" and type(previous.dispose)=="function" and previous.dispose()==true,"previous automation bundle retirement failed") end\n',
            'local modules={}\n']
    manifest={}
    for key in MODULES:
        data=sources[key]
        if not isinstance(data,bytes) or len(data)>1048576:
            raise ValueError("module byte bound/type")
        text=data.decode("utf-8").replace("\r\n","\n")
        if "\r" in text or "\x00" in text:
            raise ValueError("unsupported source encoding")
        manifest[key]=dict(path=SOURCES[key],sha256=hashlib.sha256(text.encode()).hexdigest())
        pieces.extend([f"modules.{key}=(function()\n",text,"\nend)()\n"])
    pieces.append("""
local exported={build=BUILD,revision=REVISION,capacity_profile=CAPACITY_PROFILE}
local instance,retired,fault=nil,false,nil
local ui_instance,ui_attempted=nil,false
local catalog,extension_ids,provider_ids={}, {}, {['x4-native-v1']=true}
local frozen=false
local constructing=false
local function token(value)
    return type(value)=='string' and #value>=1 and #value<=96
        and value:match('^[a-zA-Z0-9][a-zA-Z0-9_.%-]*$')~=nil
end
local function revision(value)
    return type(value)=='string' and #value==64 and value:match('^[0-9a-f]+$')~=nil
end
function exported.register_extension(descriptor)
    assert(not frozen and not retired and fault==nil,'extension catalog is closed')
    assert(type(descriptor)=='table' and getmetatable(descriptor)==nil,'plain descriptor required')
    local count=0
    for key in pairs(descriptor) do
        assert(key=='id' or key=='revision' or key=='providers' or key=='attach','unknown descriptor field')
        count=count+1
    end
    assert(count==4 and token(descriptor.id) and revision(descriptor.revision)
        and type(descriptor.attach)=='function' and type(descriptor.providers)=='table'
        and getmetatable(descriptor.providers)==nil,'invalid extension descriptor')
    assert(#catalog<16 and not extension_ids[descriptor.id],'extension duplicate or capacity')
    local providers,n={},0
    for id,rev in pairs(descriptor.providers) do
        assert(token(id) and revision(rev) and not provider_ids[id],'provider identity or collision')
        providers[id]=rev;n=n+1
    end
    assert(n>=1 and n<=16,'provider count bound')
    local copy={id=descriptor.id,revision=descriptor.revision,providers=providers,attach=descriptor.attach}
    catalog[#catalog+1]=copy;extension_ids[copy.id]=true
    for id in pairs(providers) do provider_ids[id]=true end
    return true
end
local function retire_instance()
    assert(fault==nil,fault)
    if instance then
        local ok,result=pcall(instance.dispose)
        if not ok or result~=true then
            fault="bootstrap retirement failed: "..tostring(result)
            error(fault)
        end
    end
end
local function retire_ui()
    if ui_instance then
        local previous_constructing=constructing
        constructing=true
        local ok,result=pcall(function() return ui_instance.dispose() end)
        constructing=previous_constructing
        if not ok or result~=true then
            fault='UI bootstrap retirement failed: '..tostring(result);error(fault)
        end
        ui_instance=nil
    end
end
function exported.start_ui(deps)
    assert(not constructing and not retired and fault==nil and not ui_attempted,'UI bootstrap unavailable or already attempted')
    assert(type(deps)=='table' and deps.C,'native UI dependencies required')
    ui_attempted=true;constructing=true
    local ok,result=pcall(function()
        if deps.C.IsStartmenu()~=true then return {status='NOT_START_MENU',world_session=false} end
        ui_instance=modules.startbootstrap.new{modules={menu=modules.startmenu,pipe=modules.startpipe,codec=modules.wire},
            globals=deps.globals,C=deps.C,Helper=deps.Helper,pipes=deps.pipes,build=BUILD}
        assert(type(ui_instance)=='table' and type(ui_instance.dispose)=='function' and type(ui_instance.start)=='function',
            'invalid UI bootstrap')
        local value=ui_instance.start()
        assert(type(value)=='table' and value.status=='SCHEDULED' and value.world_session==false,'UI startup did not schedule')
        return value
    end)
    constructing=false
    if not ok then
        local cleaned,why=pcall(retire_ui)
        fault='UI bootstrap failed: '..tostring(result)..(cleaned and '' or '; '..tostring(why))
        error(fault)
    end
    return result
end
function exported.dispose()
    assert(not constructing,'bundle construction in progress')
    assert(fault==nil,fault)
    if retired then return true end
    retire_ui();retire_instance()
    retired=true;instance=nil
    return true
end
function exported.new(deps)
    frozen=true
    assert(not constructing,'bundle construction in progress')
    assert(fault==nil,fault)
    assert(not retired and type(deps)=="table","bundle retired or invalid dependencies")
    assert(deps.capacity_profile==nil and deps.capacity_resolver==nil,
        'capacity selection belongs to the generated bundle')
    retire_ui();retire_instance()
    instance=nil
    constructing=true
    local candidate,native
    local owned_channels={}
    local extensions_live=true
    local cleanups,once_by_function={},{}
    local function own_cleanup(fn)
        assert(type(fn)=='function','disposer required')
        if once_by_function[fn] then return once_by_function[fn] end
        local attempted,okay,result=false,nil,nil
        local function once()
            if not attempted then
                attempted=true;okay,result=pcall(fn)
            end
            if not okay or result~=true then error('extension disposal failed: '..tostring(result)) end
            return true
        end
        once_by_function[fn]=once;cleanups[#cleanups+1]=once
        return once
    end
    local function retire_extensions()
        extensions_live=false
        local failures={}
        for index=#cleanups,1,-1 do
            local good,reason=pcall(cleanups[index])
            if not good then failures[#failures+1]=tostring(reason) end
        end
        return failures
    end
    local ok,why=pcall(function()
        assert(type(deps.read)=="function" and type(deps.read_verbs)=="table","closed legacy reads required")
        local config={}
        for key,value in pairs(deps) do config[key]=value end
        config.modules=modules;config.build=BUILD;config.revision=REVISION
        config.capacity_profile=CAPACITY_PROFILE;config.capacity_resolver=capacity_resolver
        local native_reads=modules.nativeassembly.read_verbs()
        local reads,allow={},{}
        for verb,enabled in pairs(deps.read_verbs) do
            assert(type(verb)=="string" and enabled==true and not native_reads[verb]
                and verb~='automation_capacity' and verb~='md_channel_capacity',"mixed or invalid read namespace")
            reads[verb]=true
        end
        for verb,enabled in pairs(native_reads) do
            assert(type(verb)=="string" and enabled==true,"invalid native read namespace")
            reads[verb]=true
        end
        assert(deps.provider_revisions==nil,'provider revisions belong to the installed extension catalog')
        for _,descriptor in ipairs(catalog) do
            for id,rev in pairs(descriptor.providers) do allow[id]=rev end
        end
        allow["x4-native-v1"]=BUILD
        reads.automation_capacity=true
        reads.md_channel_capacity=true
        config.read_verbs=reads;config.provider_revisions=allow
        local legacy_read=deps.read
        config.read=function(verb,args)
            if verb=='md_channel_capacity' then
                assert(type(args)=='table' and getmetatable(args)==nil and #args<=1,
                    'channel capacity takes zero or one registered extension id')
                for key in pairs(args) do assert(key==1,'unexpected channel capacity argument') end
                assert(candidate,'channel catalog unavailable')
                local requested=args[1]
                if requested~=nil then assert(token(requested),'registered extension id required') end
                local entries,found={},requested==nil
                for _,descriptor in ipairs(catalog) do
                    if requested==nil or requested==descriptor.id then
                        found=true
                        local row={extension=descriptor.id,revision=descriptor.revision,channel_count=0}
                        if requested~=nil then row.channels={} end
                        for _,owned in ipairs(owned_channels) do
                            if owned.extension==descriptor.id then
                                row.channel_count=row.channel_count+1
                                if requested~=nil then
                                    assert(type(owned.channel.capacity)=='function','channel counter unavailable')
                                    row.channels[#row.channels+1]=owned.channel.capacity()
                                end
                            end
                        end
                        entries[#entries+1]=row
                    end
                end
                assert(found,'extension is not in this attached helper catalog')
                local payload=candidate.encode({scope='ATTACHED_EXTENSION_LOCAL_CHANNELS_NOT_NATIVE_MD_LOAD_PROOF',
                    entries=entries,extensions_returned=#entries,atomic=false,reserved=false,
                    native_md_loaded_verified=false,future_fit_verified=false})
                assert(type(payload)=='string' and #payload<=32000,'channel counter read byte bound')
                return 'OK',payload
            end
            if verb=='automation_capacity' then
                assert(type(args)=='table' and next(args)==nil,'capacity read takes no arguments')
                assert(candidate and native,'capacity observers not ready')
                local current=candidate.capacity()
                current.native=native.capacity()
                current.reserved=false;current.future_fit_verified=false
                return 'OK',candidate.encode(current)
            end
            if native_reads[verb] then
                assert(native~=nil,"native assembly not ready")
                return native.read(verb,args)
            end
            assert(reads[verb]==true,"undeclared legacy read")
            return legacy_read(verb,args)
        end
        candidate=modules.bootstrap(config)
        assert(type(candidate)=="table" and type(candidate.dispose)=="function"
            and type(candidate.register_provider)=="function" and type(candidate.encode)=="function"
            and type(candidate.session)=="table" and type(candidate.session.current)=="function",
            "invalid bootstrap")
        native=modules.nativeassembly.new{modules=modules,ffi=deps.ffi,C=deps.C,globals=deps.globals,
            Helper=deps.Helper,public_current=candidate.session.current,resolve_issued=deps.resolve_issued,
            clock=deps.clock,encode=candidate.encode,build=BUILD,
            capacity_profile=CAPACITY_PROFILE,capacity_resolver=capacity_resolver}
        assert(type(native)=="table" and type(native.read)=="function" and type(native.dispose)=="function"
            and type(native.provider_spec)=="table" and native.provider_spec.id=="x4-native-v1"
            and native.provider_spec.revision==BUILD,"invalid native assembly")
        assert(candidate.register_provider(native.provider_spec)~=false,"native provider registration refused")
        for _,descriptor in ipairs(catalog) do
            local attaching,registered,hooks=true,{},0
            local function active() assert(extensions_live,'extension instance retired') end
            local function current()
                if not extensions_live then return nil end
                return candidate.session.current()
            end
            local facade={}
            function facade.register(spec)
                active();assert(attaching,'extension registration sealed')
                assert(type(spec)=='table' and getmetatable(spec)==nil
                    and token(spec.id) and revision(spec.revision)
                    and descriptor.providers[spec.id]==spec.revision and not registered[spec.id]
                    and type(spec.session)=='function' and type(spec.invoke)=='function'
                    and type(spec.actions)=='table' and type(spec.dispose)=='function',
                    'undeclared, duplicate or malformed extension provider')
                local session,invoke=spec.session,spec.invoke
                local wrapped={id=spec.id,revision=spec.revision,actions={}}
                for action,enabled in pairs(spec.actions) do wrapped.actions[action]=enabled end
                wrapped.dispose=own_cleanup(spec.dispose)
                wrapped.session=function() if extensions_live then return session() end end
                wrapped.invoke=function(phase,request,callback)
                    active()
                    return invoke(phase,request,function(...)
                        if extensions_live then return callback(...) end
                    end)
                end
                assert(candidate.register_provider(wrapped)~=false,'extension provider registration refused')
                registered[spec.id]=true
                return true
            end
            local context={public_current=current,encode=candidate.encode,build=BUILD,
                extension_id=descriptor.id,extension_revision=descriptor.revision,registry=facade,
                ffi=deps.ffi,C=deps.C,globals=deps.globals,Helper=deps.Helper,native=deps.native,
                resolve_issued=deps.resolve_issued,clock=deps.clock,
                capacity_profile=CAPACITY_PROFILE,capacity_resolver=capacity_resolver,
                capacity_revision=capacity_resolver(CAPACITY_PROFILE).revision}
            function context.order_binding(request_id)
                active();return native.order_binding(request_id)
            end
            function context.on_dispose(fn)
                active();assert(attaching and hooks<16,'extension cleanup registration closed or full')
                hooks=hooks+1;return own_cleanup(fn)
            end
            function context.create_md_channel(config)
                active();assert(attaching and hooks<16,'extension channel registration closed or full')
                local globals={}
                for _,name in ipairs({'RegisterEvent','GetNPCBlackboard','SetNPCBlackboard',
                        'AddUITriggeredEvent','ConvertStringTo64Bit','getElapsedTime'}) do
                    globals[name]=deps.native and deps.native[name] or deps.globals[name]
                end
                globals.ConvertIDTo64Bit=deps.globals.ConvertIDTo64Bit
                local channel=modules.mdchannel{config=config,ffi=deps.ffi,C=deps.C,
                    globals=globals,Helper=deps.Helper,public_current=current}
                context.on_dispose(channel.dispose)
                owned_channels[#owned_channels+1]={extension=descriptor.id,channel=channel}
                return channel
            end
            local attached,handle=pcall(descriptor.attach,context)
            attaching=false
            assert(attached,'extension attach failed: '..tostring(handle))
            assert(type(handle)=='table' and type(handle.dispose)=='function','extension lifecycle handle required')
            own_cleanup(handle.dispose)
            for id in pairs(descriptor.providers) do
                assert(registered[id],'declared extension provider not registered: '..id)
            end
        end
        local bootstrap_dispose=candidate.dispose
        candidate.dispose=function()
            local failures=retire_extensions()
            local good,result=pcall(bootstrap_dispose)
            if not good or result~=true then failures[#failures+1]=tostring(result) end
            assert(#failures==0,table.concat(failures,'; '))
            return true
        end
    end)
    if not ok then
        local cleanup=retire_extensions()
        -- Both are idempotent; retire the bootstrap callbacks even if registration
        -- partially succeeded, then any assembly not owned by that registration.
        local owners={bootstrap=candidate,native=native}
        for _,key in ipairs({"bootstrap","native"}) do
            local value=owners[key]
            if value then
                local good,result=pcall(function() return value.dispose() end)
                if not good or result~=true then cleanup[#cleanup+1]=tostring(result) end
            end
        end
        fault="automation construction failed: "..tostring(why)
        if #cleanup>0 then fault=fault.."; cleanup failed: "..table.concat(cleanup,"; ") end
        constructing=false
        error(fault)
    end
    constructing=false
    instance=candidate
    return candidate
end
_G.X4ToolkitAutomationBundle=exported
""")
    if hashlib.sha256(CAPACITY_SOURCE.read_bytes()).hexdigest()!=capacity['source_raw_sha256']:
        raise ValueError("capacity source changed during bundling")
    masked="".join(pieces).encode("utf-8")
    digest=hashlib.sha256(masked).hexdigest()
    payload=masked.replace(MARKER.encode(),('local BUILD = "'+digest+'"').encode(),1)
    return payload,dict(build=digest,revision=revision,modules=manifest,capacity=capacity,
                        normalization="UTF8_CRLF_TO_LF",sha256=hashlib.sha256(payload).hexdigest(),runtime_verified=False)


def verify(payload: bytes):
    pattern=rb'local BUILD = "([0-9a-f]{64})"'
    found=re.findall(pattern,payload)
    if len(found)!=1:
        raise ValueError("bundle must declare one exact build identity")
    masked=re.sub(pattern,MARKER.encode(),payload,count=1)
    if hashlib.sha256(masked).hexdigest()!=found[0].decode():
        raise ValueError("bundle content differs from declared build")
    return found[0].decode()

