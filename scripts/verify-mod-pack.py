#!/usr/bin/env python3
"""Refuse a mod release folder that is incomplete or would paste wrong.

Run by the x4-mod-release-review skill, Phase 6, before the folder is handed to the author. It
reads the folder and changes nothing. It reports every problem it finds, not only the first.

Usage:  python scripts/verify-mod-pack.py <release folder>
Exit:   0 every check held; 1 the pack has problems (each named); 2 the folder cannot be read

REQUIRED FILES, all in the one folder. <version> is the manifest's "version".
  an archive (.zip, .7z or .rar)    every archive in the folder must be listed in the manifest
  NEXUS-DESCRIPTION-v<version>.txt  paste file: the new page description
  NEXUS-SUMMARY-v<version>.txt      paste file: the short summary
  NEXUS-CHANGELOG-v<version>.txt    paste file: one change per line, at most 120 characters each
  description-BEFORE-v<version>.txt the previous page text, for rollback (see THE ROLLBACK COPY)
  UPLOAD-NOTES.md                   the steps left for the author
  SHIPPED-MANIFEST.json             see below
  REVIEW-RECORD.md                  the baseline, the tested set, every finding and its answer
Other files and subfolders are allowed and are not examined. An empty file, or one holding only
whitespace (a non-breaking space included) or invisible characters such as a zero-width space,
counts as empty.

A PASTE FILE is pasted whole into a web form, so it must be in the form the editor accepts. It is
refused for:
  - any "<br" tag, or any HTML entity such as "&amp;" or "&#92;". Those are the form the Nexus API
    hands back. A bare "&" is fine.
  - any carriage return (CRLF line endings)
  - text that is not valid UTF-8
  - a header line, which would be pasted onto the page along with the text. A header line is:
      * a first non-blank line starting with "#", or a later line that is a markdown heading or
        comment ("#" to "######" followed by a space or the end of the line). "#1 cause" further
        down is ordinary text.
      * a first non-blank line of the form "Key: value" whose key is metadata: mod, mod name, name,
        title, version, file, filename, date, generated, generated by, built, source, author,
        game, nexus, url, sha256, hash, description, summary, changelog. The list is closed on
        purpose: "Fixed: a crash on load" is an ordinary first line of a changelog, so "any
        Key: value" would refuse good files.

THE ROLLBACK COPY is the previous page as it was, so its wording is not judged: a line such as
"Version: 1.1.0" or "# Install", or a literal "&lt;", may be what that page said, and changing it would
make the rollback wrong. It is pasted back, so its form is judged: UTF-8, LF line endings, no control
bytes and no <br. It must exist, carry the manifest's version in its name,
not be empty, and, if the manifest lists it ("files" with its plain name as the path, or "archives"),
match that row's sha256 and size.

SHIPPED-MANIFEST.json is a UTF-8 JSON object:
  {
    "mod": "my_mod",
    "version": "1.2.0",
    "status": "shipped",
    "archives": [{"name": "my_mod-1.2.0.zip", "sha256": "<64 hex>", "size": 12345}],
    "files": [{"path": "ext_01.cat", "sha256": "<64 hex>", "size": 67890}]
  }
"mod" must be a non-empty string. "archives" lists every download in this folder, by plain file
name, hashed as uploaded. "files" lists every file packed inside the release. "version" must match
the versioned file names above, and "status" must be "shipped". Other keys are allowed. A field of
the wrong type is reported like any other problem.

WHAT THIS DOES NOT CHECK. It does not open an archive, compare "files" with anything, tell whether
the description was really built from the live page, or read the prose. A clean run says the folder
has the right shape and paste form. It does not say the text is right.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import unicodedata
from pathlib import Path
from typing import NamedTuple

BOM = b"\xef\xbb\xbf"
CHANGELOG_LINE_LIMIT = 120
ARCHIVE_SUFFIXES = (".zip", ".7z", ".rar")
MANIFEST_NAME = "SHIPPED-MANIFEST.json"
SHA256 = re.compile(r"[0-9a-fA-F]{64}")
BR = re.compile(r"<br", re.I)
ENTITY = re.compile(r"&(?:[A-Za-z][A-Za-z0-9]*|#[0-9]+|#[xX][0-9a-fA-F]+);")
LATER_HEADING = re.compile(r"\s*#{1,6}(?:\s|$)")
KEY_VALUE = re.compile(r"\s*([A-Za-z][A-Za-z0-9 _-]*?)\s*:(?:\s|$)")
METADATA_KEYS = frozenset((
    "mod", "mod name", "name", "title", "version", "file", "filename", "date", "generated",
    "generated by", "built", "source", "author", "game", "nexus", "url", "sha256", "hash",
    "description", "summary", "changelog",
))


class PasteFile(NamedTuple):
    prefix: str
    suffix: str
    is_changelog: bool = False


PASTE_FILES = (
    PasteFile("NEXUS-DESCRIPTION-v", ".txt"),
    PasteFile("NEXUS-SUMMARY-v", ".txt"),
    PasteFile("NEXUS-CHANGELOG-v", ".txt", True),
)
ROLLBACK = PasteFile("description-BEFORE-v", ".txt")
VERSIONED_FILES = (*PASTE_FILES, ROLLBACK)
OTHER_REQUIRED = ("UPLOAD-NOTES.md", "REVIEW-RECORD.md")


class Problem(NamedTuple):
    code: str
    file: str
    detail: str


class Result(NamedTuple):
    problems: list
    paste_files: int
    changelog_lines: int
    archives_matched: int


class PackUnreadable(Exception):
    """The folder itself cannot be looked at, so nothing can be said about the pack."""


def required_label(name: str) -> str:
    """How a required file is named in a report: its version becomes `<version>`."""
    for spec in VERSIONED_FILES:
        if name.startswith(spec.prefix) and name.endswith(spec.suffix):
            return spec.prefix + "<version>" + spec.suffix
    return name


def _read(path: Path) -> bytes:
    with open(path, "rb") as handle:
        return handle.read()


def _sha256(path: Path) -> tuple[str, int]:
    digest = hashlib.sha256()
    size = 0
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
            size += len(chunk)
    return digest.hexdigest(), size


def _blank(data: bytes) -> bool:
    """Nothing a reader would see: whitespace, format characters (zero-width and the like) and controls."""
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:  # silent-ok: text that cannot decode is not blank; each caller reports the encoding
        return False
    return all(c.isspace() or unicodedata.category(c) in ("Cf", "Cc") for c in text)


def _load(folder: Path, name: str, problems: list) -> bytes | None:
    """The file's bytes, or None once the reason it has none is on the problem list."""
    path = folder / name
    if not path.is_file():
        problems.append(Problem("unreadable", name, "this is not a file"))
        return None
    try:
        data = _read(path)
    except OSError as exc:
        problems.append(Problem("unreadable", name, str(exc)))
        return None
    if _blank(data):
        problems.append(Problem("empty", name, "the file has no content"))
        return None
    return data


def _header_line(lines: list) -> int:
    """The 1-based number of the first header line, or 0 if there is none (see the module help)."""
    first = next((i for i, line in enumerate(lines) if line.strip()), None)
    if first is None:
        return 0
    if lines[first].lstrip().startswith("#"):
        return first + 1
    match = KEY_VALUE.match(lines[first])
    if match and match.group(1).casefold() in METADATA_KEYS:
        return first + 1
    for i in range(first + 1, len(lines)):
        if LATER_HEADING.match(lines[i]):
            return i + 1
    return 0


def _first_line(text: str, start: int) -> int:
    return text.count("\n", 0, start) + 1


def _check_paste(name: str, data: bytes, is_changelog: bool, problems: list) -> int:
    """Check one paste file; return its count of non-blank changelog lines."""
    returns = data.count(b"\r")
    if returns:
        problems.append(Problem("crlf", name, f"{returns} carriage return(s); use LF line endings"))
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        problems.append(Problem("not-utf8", name, str(exc)))
        return 0
    for code, pattern, what in (("br", BR, "<br tag(s)"), ("entity", ENTITY, "HTML entity(ies)")):
        hits = list(pattern.finditer(text))
        if hits:
            problems.append(Problem(code, name, f"{len(hits)} {what}, first on line "
                                                f"{_first_line(text, hits[0].start())}: {hits[0].group(0)}"))
    lines = [line.rstrip("\r") for line in text.split("\n")]
    header = _header_line(lines)
    if header:
        problems.append(Problem("header", name, f"line {header} would be pasted onto the page: "
                                                f"{lines[header - 1][:60]}"))
    if not is_changelog:
        return 0
    for number, line in enumerate(lines, 1):
        if len(line) > CHANGELOG_LINE_LIMIT:
            problems.append(Problem("line-too-long", name, f"line {number} has {len(line)} characters; "
                                                           f"the limit is {CHANGELOG_LINE_LIMIT}"))
    return sum(1 for line in lines if line.strip())


def _check_rollback(name: str, data: bytes, file_rows: list, problems: list) -> None:
    """Its wording is never judged, but it is pasted over the page on a rollback, so its form is: UTF-8 with no control
    bytes, no carriage return and no raw `<br`, the API's form that step 3 converts. Then any manifest row for it."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = None
    if text is None or "\r" in text or "<br" in text.lower() or any(ord(c) < 32 and c not in "\n\t" for c in text):
        problems.append(Problem("rollback-form", name, "not in the editor's form: it must be UTF-8 with LF line "
                                "endings and no <br, converted as the skill's step 3 says, with the wording unchanged"))
    for row in file_rows:
        if row["path"] != name:
            continue
        digest = hashlib.sha256(data).hexdigest()
        if digest != row["sha256"].lower():
            problems.append(Problem("rollback-hash", name, f'sha256 is {digest}; the manifest says {row["sha256"]}'))
        if len(data) != row["size"]:
            problems.append(Problem("rollback-size", name, f'size is {len(data)}; the manifest says {row["size"]}'))


def _plain_name(name: str) -> bool:
    return (name not in ("", ".", "..") and not any(c in name for c in "/\\:"))


def _hash_field_ok(row: dict) -> bool:
    value = row.get("sha256")
    return isinstance(value, str) and SHA256.fullmatch(value) is not None


def _size_field_ok(row: dict) -> bool:
    value = row.get("size")
    return type(value) is int and value >= 0


def _rows(data: dict, key: str, id_field: str, problems: list) -> list:
    """The manifest's well-formed rows under *key*; every malformed one goes on the problem list."""
    rows = data.get(key)
    if not isinstance(rows, list) or not rows:
        problems.append(Problem("manifest", MANIFEST_NAME, f'"{key}" must be a non-empty list'))
        return []
    good = []
    for i, row in enumerate(rows):
        label = f"{key}[{i}]"
        if not isinstance(row, dict):
            problems.append(Problem("manifest", MANIFEST_NAME, f"{label} must be an object"))
            continue
        wrong = []
        ident = row.get(id_field)
        if not isinstance(ident, str) or not ident:
            wrong.append(f'"{id_field}" must be a non-empty string')
        elif key == "archives" and not _plain_name(ident):
            wrong.append(f'"{id_field}" must be a plain file name in this folder')
        if not _hash_field_ok(row):
            wrong.append('"sha256" must be 64 hex characters')
        if not _size_field_ok(row):
            wrong.append('"size" must be a whole number')
        if wrong:
            problems.append(Problem("manifest", MANIFEST_NAME, f"{label}: " + "; ".join(wrong)))
        else:
            good.append(row)
    return good


def _check_archives(folder: Path, names: list, rows: list, problems: list) -> int:
    """Hash every listed archive against its row; return how many matched."""
    present = set(names)
    matched = 0
    for row in rows:
        name = row["name"]
        if name not in present:
            problems.append(Problem("archive-missing", name, "the manifest lists it; it is not in the folder"))
            continue
        path = folder / name
        if not path.is_file():
            problems.append(Problem("unreadable", name, "this is not a file"))
            continue
        try:
            digest, size = _sha256(path)
        except OSError as exc:
            problems.append(Problem("unreadable", name, str(exc)))
            continue
        good = True
        if size == 0:
            problems.append(Problem("empty", name, "the archive has no content"))
            good = False
        if digest != row["sha256"].lower():
            problems.append(Problem("archive-hash", name, f'sha256 is {digest}; the manifest says {row["sha256"]}'))
            good = False
        if size != row["size"]:
            problems.append(Problem("archive-size", name, f'size is {size}; the manifest says {row["size"]}'))
            good = False
        matched += good
    return matched


def check_pack(folder: Path) -> Result:
    """Every problem in the release folder. Raises PackUnreadable if it cannot be listed at all."""
    folder = Path(folder)
    try:  # A missing path, or a file given as the folder, raises here too.
        names = sorted(os.listdir(folder))
    except OSError as exc:
        raise PackUnreadable(f"cannot list {folder}: {exc}") from exc

    problems: list = []
    version = None
    archive_rows = None
    listed_names: set = set()
    file_rows: list = []

    # The manifest goes first: it supplies the version the file names are held to.
    if MANIFEST_NAME not in names:
        problems.append(Problem("missing", MANIFEST_NAME, "required file"))
    else:
        raw = _load(folder, MANIFEST_NAME, problems)
        if raw is not None:
            try:
                data = json.loads(raw.decode("utf-8-sig"))
            except (ValueError, RecursionError) as exc:
                data = None
                problems.append(Problem("manifest", MANIFEST_NAME, f"not readable as JSON: {exc}"))
            if data is not None and not isinstance(data, dict):
                problems.append(Problem("manifest", MANIFEST_NAME, "the top level must be a JSON object"))
            elif isinstance(data, dict):
                mod_name = data.get("mod")
                if not isinstance(mod_name, str) or not mod_name.strip():
                    problems.append(Problem("manifest", MANIFEST_NAME, '"mod" must be a non-empty string'))
                candidate = data.get("version")
                if isinstance(candidate, str) and candidate.strip():
                    version = candidate
                else:
                    problems.append(Problem("manifest", MANIFEST_NAME, '"version" must be a non-empty string'))
                if data.get("status") != "shipped":
                    problems.append(Problem("manifest", MANIFEST_NAME, '"status" must be "shipped"'))
                archive_rows = _rows(data, "archives", "name", problems)
                raw_rows = data.get("archives")
                if isinstance(raw_rows, list) and raw_rows:
                    # A row already refused as malformed still says the author meant that file,
                    # so its archive is not also reported as unlisted.
                    # A name that is not a string is no file's name, and a list could not be held in a set.
                    listed_names = {r.get("name") for r in raw_rows
                                    if isinstance(r, dict) and isinstance(r.get("name"), str)}
                else:
                    archive_rows = None
                file_rows = _rows(data, "files", "path", problems)

    paste_count = 0
    changelog_lines = 0
    for spec in VERSIONED_FILES:
        label = spec.prefix + "<version>" + spec.suffix
        matches = [n for n in names if n.startswith(spec.prefix) and n.endswith(spec.suffix)]
        if not matches:
            problems.append(Problem("missing", label, "required file"))
            continue
        if len(matches) > 1:
            problems.append(Problem("ambiguous", label, "keep one of: " + ", ".join(matches)))
            continue
        name = matches[0]
        if version is not None and name != spec.prefix + version + spec.suffix:
            problems.append(Problem("wrong-version", name, f"the manifest's version is {version}"))
        data = _load(folder, name, problems)
        if data is None:
            continue
        if spec is ROLLBACK:
            _check_rollback(name, data, file_rows, problems)
            continue
        paste_count += 1
        changelog_lines += _check_paste(name, data, spec.is_changelog, problems)

    for name in OTHER_REQUIRED:
        if name not in names:
            problems.append(Problem("missing", name, "required file"))
        else:
            _load(folder, name, problems)

    archives_here = [n for n in names if n.casefold().endswith(ARCHIVE_SUFFIXES)]
    if not archives_here:
        problems.append(Problem("missing", "<archive>", "no .zip, .7z or .rar in the folder"))
    matched = 0
    # With no usable manifest there is nothing to compare an archive to, and that is already reported.
    if archive_rows is not None:
        matched = _check_archives(folder, names, archive_rows, problems)
        for name in archives_here:
            if name not in listed_names:
                problems.append(Problem("archive-unlisted", name, 'not in the manifest\'s "archives"'))
    return Result(problems, paste_count, changelog_lines, matched)


def main(argv: list | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(prog="verify-mod-pack.py", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("folder", type=Path, help="the release folder to check")
    args = parser.parse_args(argv)
    try:
        result = check_pack(args.folder)
    except PackUnreadable as exc:
        print(f"PACK REFUSED: {exc}", file=sys.stderr)
        return 2
    if result.problems:
        print(f"PACK REFUSED: {len(result.problems)} problem(s) in {args.folder}")
        for problem in result.problems:
            print(f"  [{problem.code}] {problem.file}: {problem.detail}")
        return 1
    print(f"PACK OK: {args.folder}")
    print(f"  {result.paste_files} paste file(s) checked, rollback copy present, "
          f"{result.changelog_lines} changelog line(s), {result.archives_matched} archive(s) matched the manifest.")
    print("  Not checked: the archive's contents, the prose, the rollback copy's text, "
          "or where the description came from.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
